"""Makes the comparison pictures of the README (docs/images/compare-*.png) from our own atlas deck.

The atlas is generated by our harness and is CC0. Each picture puts two renders side by side:
  left   the atlas PDF's page, drawn by MuPDF (the input the converter reads);
  right  the converted PPTX, drawn by PowerPoint (the render the fidelity run already made),
and says how many editable objects (text boxes, shapes, lines, pictures, groups, tables/charts) that PPTX slide holds.
No tier-B or private deck is ever used. Needs a local fidelity run (out/atlas, out/fidelity/atlas/std):

  harness/.venv/Scripts/python scripts/make-comparison-images.py [--out docs/images]

Then add the new SHA-256 values to IMAGE_ALLOWLIST in scripts/check-no-binaries.mjs (the script prints them).
"""
import argparse
import hashlib
import re
import sys
import zipfile
from io import BytesIO
from pathlib import Path

import fitz
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
PDF = ROOT / "out" / "atlas" / "atlas_std.pdf"
PPTX = ROOT / "out" / "fidelity" / "atlas" / "std" / "out.pptx"
RENDERS = ROOT / "out" / "fidelity" / "atlas" / "std" / "render"

# (file name, 1-based page = slide of the converted deck, caption)
PICTURES = [
    ("compare-shapes", 1, "Shapes (atlas shapes/01)"),
    ("compare-fills", 40, "Fills and gradients (atlas)"),
    ("compare-text", 72, "Text (atlas)"),
    ("compare-table", 114, "Table (atlas)"),
]
OBJECT_TAGS = ("p:sp", "p:pic", "p:cxnSp", "p:grpSp", "p:graphicFrame")
PANEL_W = 600
MAX_BYTES = 300 * 1024


def count_objects(pptx: Path, slide: int) -> int:
    with zipfile.ZipFile(pptx) as z:
        xml = z.read(f"ppt/slides/slide{slide}.xml").decode("utf-8")
    tree = re.sub(r"<p:nvGrpSpPr>.*?</p:nvGrpSpPr>", "", xml, count=1, flags=re.S)  # the slide's own root group is not an object
    return sum(len(re.findall(rf"<{tag}[ >]", tree)) for tag in OBJECT_TAGS)


def font(size: int):
    for name in ("malgun.ttf", "arial.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default(size)


def render_pdf(doc, page: int) -> Image.Image:
    p = doc[page - 1]
    zoom = PANEL_W / p.rect.width
    pix = p.get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
    return Image.open(BytesIO(pix.tobytes("png"))).convert("RGB")


def make(name: str, page: int, caption: str, out: Path) -> Path:
    doc = fitz.open(PDF)
    left = render_pdf(doc, page)
    right = Image.open(RENDERS / f"slide{page}.png").convert("RGB")
    right = right.resize((PANEL_W, round(right.height * PANEL_W / right.width)), Image.LANCZOS)
    objects = count_objects(PPTX, page)
    gap, head, foot = 16, 34, 30
    h = max(left.height, right.height)
    canvas = Image.new("RGB", (PANEL_W * 2 + gap * 3, head + h + foot), "white")
    d = ImageDraw.Draw(canvas)
    f, fb = font(16), font(14)
    d.text((gap, 8), "PDF (MuPDF)", fill="black", font=f)
    d.text((PANEL_W + gap * 2, 8), "converted PPTX (PowerPoint)", fill="black", font=f)
    for x in (gap, PANEL_W + gap * 2):
        d.rectangle((x - 1, head - 1, x + PANEL_W, head + h), outline=(160, 160, 160))
    canvas.paste(left, (gap, head))
    canvas.paste(right, (PANEL_W + gap * 2, head))
    d.text((gap, head + h + 7), f"{caption}. The PPTX slide holds {objects} editable objects.", fill=(60, 60, 60), font=fb)
    target = out / f"{name}.png"
    # 256 colours keeps flat slides small; the picture is a README illustration, not a measurement
    canvas.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).save(target, optimize=True)
    if target.stat().st_size > MAX_BYTES:
        raise SystemExit(f"{target} is {target.stat().st_size} bytes, over {MAX_BYTES}")
    return target


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "images"))
    args = ap.parse_args()
    for path in (PDF, PPTX, RENDERS):
        if not path.exists():
            print(f"missing {path}: run a local atlas fidelity run first", file=sys.stderr)
            return 1
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, page, caption in PICTURES:
        target = make(name, page, caption, out)
        print(f"{target.relative_to(out).as_posix()}\t{target.stat().st_size}\t{hashlib.sha256(target.read_bytes()).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
