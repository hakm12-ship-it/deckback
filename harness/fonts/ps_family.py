"""The PostScript-name table (M4 Task 3): PostScript names of known fonts to their family, for fonts a PDF names only.

    harness/.venv/Scripts/python -m harness.fonts.ps_family [--ts <file>]

A PDF names a font by its PostScript name (/BaseFont: `MalgunGothicBold`, `Arial-BoldMT`, `TimesNewRoman,Bold`), and a
font that is not embedded, or whose program has no name table, has nothing else. PowerPoint needs the family name (nameID
1, the typeface name: `Malgun Gothic`); a typeface without its spaces (`MalgunGothic`) is a font PowerPoint does not
have, and it draws the text in another. deckback's lowering (packages/core/src/fonts/names.ts) finds the family through
`packages/core/src/fonts/ps-family.ts`, which this writes: each PostScript name (nameID 6) mapped to its family (nameID
1) and its style (nameID 2).

Ruling M4-R8: the table names only families of public sources, and is the same on any machine. So no font file is read.
Its faces come from two committed lists (`build`):
- harness/fonts/ps-family.json, curated: the faces of spec section 7's Windows and Office families (`SPEC_FAMILIES`,
  and the families starting with `SPEC_PREFIXES`: the HY and Nanum families) and of the atlas-win build's Windows fonts
  (`atlas_win_families`), as those fonts ship;
- harness/fonts/fonts.lock.json: the OFL fonts the public decks embed, each file's `postscriptName` under its family, its
  style the full name past the family (Regular when nothing is left).
A face whose family is of no source, or a PostScript name given twice, is refused (ValueError). The file holds font names
and style names only. It is committed; the harness reads its families back (`known_families`) for S6's check of
typefaces without their spaces (harness/fidelity/structural.py).
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DEFAULT_TS = REPO / "packages" / "core" / "src" / "fonts" / "ps-family.ts"
LOCK = Path(__file__).with_name("fonts.lock.json")
CURATED = Path(__file__).with_name("ps-family.json")

# Spec section 7's list (ruling M4-R8): its families, and the families its HY and Nanum families start with.
SPEC_FAMILIES = ("Malgun Gothic", "Gulim", "Batang", "Dotum", "Gungsuh", "Noto Sans KR", "Pretendard", "Arial",
                 "Calibri", "Segoe UI", "Times New Roman", "Cambria", "Consolas")
SPEC_PREFIXES = ("HY", "Nanum")

TS_HEAD = """/**
 * The PostScript names (nameID 6) of known fonts, each with its family (nameID 1, the typeface name PowerPoint takes) and
 * its style (nameID 2): the Windows and Office fonts of spec section 7's list and of the atlas-win build
 * (harness/fonts/ps-family.json) and the OFL fonts of harness/fonts/fonts.lock.json, public sources only (ruling M4-R8).
 * `familyOfPostScript` (names.ts) reads it.
 *
 * Generated by `python -m harness.fonts.ps_family` from those two lists: do not edit it by hand. Font names and style
 * names only.
 */
export const PS_FAMILY: Readonly<Record<string, readonly [family: string, style: string]>> = """
TS_TAIL = ";\n"
_TS_BODY = re.compile(r"export const PS_FAMILY: [^=]+= (\{.*\});", re.S)
# A name: printable, and nothing a path could need.
_BAD_NAME = re.compile(r"[\x00-\x1f\x7f/\\:*?\"<>|]")


def lock_families(lock=LOCK):
    """The families of fonts.lock.json."""
    return [fam["family"] for fam in json.loads(Path(lock).read_text(encoding="utf-8"))["families"]]


def atlas_win_families():
    """The Windows families the atlas-win build uses (harness/atlas/deck.py ROLES['windows'], and the emoji slide's
    harness/atlas/sections/text.py EMOJI_FONT)."""
    from harness.atlas.deck import ROLES
    from harness.atlas.sections.text import EMOJI_FONT

    return {font.family for font in ROLES["windows"].values()} | {EMOJI_FONT}


def allowed(family, lock=LOCK):
    """Whether `family` is of a public source (ruling M4-R8): spec section 7's list, the lock or atlas-win."""
    return (family in SPEC_FAMILIES or family.startswith(SPEC_PREFIXES) or family in lock_families(lock)
            or family in atlas_win_families())


def lock_faces(lock=LOCK):
    """{PostScript name: [family, style]} of fonts.lock.json: each file's `postscriptName` under its family, its style
    its `fullName` past the family's name (Regular when nothing is left, or the full name is not the family's)."""
    out = {}
    for fam in json.loads(Path(lock).read_text(encoding="utf-8"))["families"]:
        for file in fam["files"]:
            full, family = file["fullName"], fam["family"]
            style = full[len(family):].strip() if full.startswith(family) else ""
            out[file["postscriptName"]] = [family, style or "Regular"]
    return out


def build(curated=CURATED, lock=LOCK):
    """{PostScript name: [family, style]} of the curated list and the lock, in name order. ValueError for a family of
    no public source (`allowed`) or a PostScript name given twice."""
    faces = [(ps, [family, style]) for ps, family, style in json.loads(Path(curated).read_text(encoding="utf-8"))["faces"]]
    faces += list(lock_faces(lock).items())
    table = {}
    for ps, value in faces:
        if not allowed(value[0], lock):
            raise ValueError(f"{ps}: the family {value[0]!r} is of no public source (ruling M4-R8)")
        if ps in table:
            raise ValueError(f"the PostScript name {ps!r} is given twice")
        table[ps] = value
    return {ps: table[ps] for ps in sorted(table)}


def _check(table):
    for ps, value in table.items():
        if not isinstance(ps, str) or not ps or _BAD_NAME.search(ps):
            raise ValueError(f"not a PostScript name: {ps!r}")
        if (not isinstance(value, list) or len(value) != 2
                or not all(isinstance(v, str) and v.strip() and not _BAD_NAME.search(v) for v in value)):
            raise ValueError(f"{ps}: [family, style], not {value!r}")


def render_ts(table):
    """The module `ps-family.ts` of `table` ({PostScript name: [family, style]}): one entry a line, in name order."""
    _check(table)
    dump = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731
    lines = [f"  {dump(ps)}: [{dump(table[ps][0])}, {dump(table[ps][1])}]," for ps in sorted(table)]
    if lines:
        lines[-1] = lines[-1][:-1]
    return TS_HEAD + "{\n" + "\n".join(lines) + "\n}" + TS_TAIL


def parse_ts(text):
    """`PS_FAMILY` of a file `render_ts` wrote, as a dict."""
    found = _TS_BODY.search(text)
    if found is None:
        raise ValueError("not a ps-family.ts this script wrote")
    return json.loads(found.group(1))


def known_families(path=DEFAULT_TS):
    """The families of the committed table (its values' families), a set."""
    return {family for family, _ in parse_ts(Path(path).read_text(encoding="utf-8")).values()}


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write the PostScript-name table of known fonts.")
    parser.add_argument("--ts", type=Path, default=DEFAULT_TS, help="the ps-family.ts to write")
    args = parser.parse_args(argv)
    table = build()
    args.ts.write_text(render_ts(table), encoding="utf-8", newline="\n")
    families = sorted({family for family, _ in table.values()})
    print(f"{len(table)} PostScript names, {len(families)} families: {', '.join(families)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
