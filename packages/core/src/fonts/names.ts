import { familyOfName, SUBSET_TAG } from '../scene/fonts';
import { PS_FAMILY } from './ps-family';
import { capName, NAME_MAX_TYPEFACE } from './sfnt';

/**
 * Font names to the family PowerPoint knows (M4 Task 3, spec §7 "글꼴 이름이 진짜 가족 이름이다"). A PDF names a font by its
 * PostScript name (/BaseFont: `MalgunGothicBold`, `Arial-BoldMT`, Office's `TimesNewRoman,Bold`); a font that is not
 * embedded, or whose program has no name table, has nothing else, and a typeface without its spaces (`MalgunGothic`) is a
 * font PowerPoint does not have, so it draws the text in another. `PS_FAMILY` (ps-family.ts, generated by
 * harness/fonts/ps_family.py from its curated list and the font lock: public families only, ruling M4-R8) maps the
 * PostScript names of known fonts to their family and style.
 *
 * `familyOfPostScript` goes in this order:
 * 1. the subset tag (`ABCDEF+`) comes off;
 * 2. the name is looked up: a PostScript name of the table (its family and style), a family of the table, a family of
 *    the table without its spaces (`TimesNewRoman`, `NotoSansKR`, `GothicA1`) or with hyphens for them (`Noto-Sans-KR`);
 * 3. else the style suffix comes off (`,Bold`, `,BoldItalic`, `-Bold`, `-SemiBold`, `-Light`, `BoldItalic` run on
 *    after the name, ...: `STYLE_SUFFIX`) and what is left is looked up as in 2. Bold and Italic are the style's; a weight
 *    (Light, SemiBold, Black, ...) is the family of that weight where the table has one (`Pretendard Light`, `Malgun
 *    Gothic Semilight`), else the family, not bold;
 * 4. else nothing (null): a name the table does not know stays as the PDF has it. A name without spaces becomes a spaced
 *    family only when the table has that family, so a family that is spelled without spaces (`NanumGothic`) or that the
 *    table does not know is never split.
 */

/** A font's family and the style its name says. */
export interface NamedFamily {
  family: string;
  bold: boolean;
  italic: boolean;
}

/**
 * A style at the end of a PostScript name, after `,` or `-` or run on: a weight and a slope, either or both. The name
 * before it is the shortest that leaves a whole style.
 */
const STYLE_SUFFIX =
  /^(.+?)[,-]?((?:Thin|Hairline|ExtraLight|UltraLight|SemiLight|DemiLight|Light|Regular|Normal|Book|Roman|Plain|Medium|SemiBold|DemiBold|ExtraBold|UltraBold|Bold|Black|Heavy)?(?:Italic|Oblique)?)$/i;

/** A weight that is the regular weight or bold, for which no family of that weight is looked for. */
const PLAIN_WEIGHT = /^(?:regular|normal|book|roman|plain|bold)?$/i;

const isBold = (style: string): boolean => /(?:^|[^a-z])bold/i.test(style); // Bold, Bold Italic; not SemiBold or ExtraBold
const isItalic = (style: string): boolean => /italic|oblique/i.test(style);

/** The families of the table, and each by its name without spaces (where that differs) and in lower case. */
const BY_PS = new Map(Object.entries(PS_FAMILY));
const FAMILIES = new Set([...BY_PS.values()].map(([family]) => family));
const SPACELESS = new Map<string, string>();
const FOLDED = new Map<string, string>();
for (const family of [...FAMILIES].sort()) {
  const bare = family.replaceAll(' ', '');
  if (bare !== family && !FAMILIES.has(bare) && !SPACELESS.has(bare)) SPACELESS.set(bare, family);
  if (!FOLDED.has(family.toLowerCase())) FOLDED.set(family.toLowerCase(), family);
}

/** Whether `name` is a family of the table. Exported for ps-family.test.ts, which checks the table through it. */
export function isKnownFamily(name: string): boolean {
  return FAMILIES.has(name);
}

/** The family of the table that `name` is without its spaces (`MalgunGothic`: `Malgun Gothic`), else null. */
export function spacelessFamily(name: string): string | null {
  return SPACELESS.get(name) ?? null;
}

/**
 * Step 2: a PostScript name of the table, a family of the table, one without its spaces, or one with hyphens for its
 * spaces (PowerPoint's export names a variable font's instance so: `Noto-Sans-KR`).
 */
function lookUp(name: string): NamedFamily | null {
  const entry = BY_PS.get(name);
  if (entry !== undefined) return { family: entry[0], bold: isBold(entry[1]), italic: isItalic(entry[1]) };
  const hyphened = name.replaceAll('-', ' ');
  const family = FAMILIES.has(name) ? name : (SPACELESS.get(name) ?? (FAMILIES.has(hyphened) ? hyphened : undefined));
  return family === undefined ? null : { family, bold: false, italic: false };
}

/** The family PowerPoint knows of the font a PDF names `name`, and the style the name says; null when the table does not know it. */
export function familyOfPostScript(name: string): NamedFamily | null {
  const bare = name.replace(SUBSET_TAG, '');
  if (bare === '') return null;
  const whole = lookUp(bare);
  if (whole !== null) return whole;
  const m = STYLE_SUFFIX.exec(bare);
  if (m === null || m[2] === '') return null;
  const base = lookUp(m[1]!);
  if (base === null) return null;
  const style = m[2]!;
  const weight = style.replace(/(?:italic|oblique)$/i, '');
  const weighted = PLAIN_WEIGHT.test(weight) ? undefined : FOLDED.get(`${base.family} ${weight}`.toLowerCase());
  return {
    family: weighted ?? base.family,
    bold: base.bold || isBold(weight),
    italic: base.italic || isItalic(style),
  };
}

/** The names of a font's program `numberedFamily` reads: nameID 1, 2, 4, 6, 16 and 17 (English, else first; null for none). */
export interface ProgramNames {
  family: string | null;
  subfamily: string | null;
  full: string | null;
  postscript: string | null;
  typoFamily: string | null;
  typoSubfamily: string | null;
}

/** A name that is a number alone (PowerPoint names a font it embedded in a deck so: `1`, `2`, `11`). */
const NUMBER = /^\s*\d+\s*$/;

/** A weight of a style (nameID 2 or 17) without its slope, null for the regular weight and bold (Windows' family model). */
function weightOf(style: string | null): string | null {
  const weight = (style ?? '').replace(/\s*(?:italic|oblique)\s*$/i, '').trim();
  return weight === '' || PLAIN_WEIGHT.test(weight) ? null : weight;
}

/**
 * M8 round 1a: the family of a font whose program's family (nameID 1) is a number alone, which no PC has: PowerPoint
 * gives a font it embeds in a deck (`ppt/fonts`) such a name, and its PDF export embeds the font so (b-d629f67e73's
 * Catamaran is `1`, `2` and `11`). Its own family is still in its other names, in this order:
 * 1. the typographic family (nameID 16), with the weight of the typographic subfamily (17) where it is not the regular
 *    weight or bold, as Windows names such a family (`Catamaran` + `Light`: `Catamaran Light`);
 * 2. the full name (nameID 4) without the number before it and the style (nameID 2) after it (`2Proxima Nova Bold`:
 *    `Proxima Nova`);
 * 3. the PostScript name (nameID 6): its family through `familyOfPostScript` (the table), else without its style suffix,
 *    a weight that is not the regular one or bold kept as above (`Catamaran-Bold`: `Catamaran`; `Catamaran-Light`:
 *    `Catamaran Light`).
 * Null for a family that is no number, and where none of them gives a name that is not a number.
 */
export function numberedFamily(names: ProgramNames): string | null {
  if (names.family === null || !NUMBER.test(names.family)) return null;
  const usable = (name: string | null | undefined): string | null => (name === null || name === undefined || name.trim() === '' || NUMBER.test(name) ? null : name.trim());
  const typo = usable(names.typoFamily);
  if (typo !== null) {
    const weight = weightOf(names.typoSubfamily);
    return weight === null ? typo : `${typo} ${weight}`;
  }
  const number = names.family.trim();
  let full = names.full?.trim() ?? '';
  if (full.startsWith(number)) full = full.slice(number.length).trim();
  const style = names.subfamily?.trim() ?? '';
  if (style !== '' && full.toLowerCase().endsWith(style.toLowerCase())) full = full.slice(0, full.length - style.length).trim();
  const fromFull = usable(full);
  if (fromFull !== null) return fromFull;
  const ps = usable(names.postscript);
  if (ps === null) return null;
  const known = familyOfPostScript(ps);
  if (known !== null) return known.family;
  const m = STYLE_SUFFIX.exec(ps);
  if (m === null || m[2] === '') return ps;
  const weight = weightOf(m[2]!);
  const base = m[1]!;
  return usable(weight === null ? base : `${base} ${weight}`);
}

/** What `typefaceFamily` reads of a font. */
export interface NamedFont {
  baseFont: string;
  latinName: string | null;
  embedded: boolean;
}

/**
 * The family lowering names a font by (`a:latin`), and the style its name says:
 * - an embedded font with a family name of its own (nameID 1): that name, but where it is no family of the table and the
 *   table knows it as a PostScript name or a family without its spaces, the table's (`MalgunGothic` is `Malgun Gothic`);
 *   its style is the font's own (FontInfo), so none from the name;
 * - a font that is not embedded, or whose program gave no names: its PostScript name (`baseFont`) through
 *   `familyOfPostScript`, its style included (FontInfo has none for it), else the family the Scene took from the name
 *   (`latinName`: the name without its subset tag and style), else none (null).
 */
export function typefaceFamily(font: NamedFont): NamedFamily | null {
  const found = typefaceFamilyUncapped(font);
  if (found === null) return null;
  // M8 I2: anything used as a typeface (here a name taken from the PDF's BaseFont too) is at most NAME_MAX_TYPEFACE characters
  const family = capName(found.family, NAME_MAX_TYPEFACE);
  return family === null ? null : family === found.family ? found : { ...found, family };
}

function typefaceFamilyUncapped(font: NamedFont): NamedFamily | null {
  const own = font.latinName === null || font.latinName === '' ? null : font.latinName;
  if (font.embedded && own !== null) {
    const known = FAMILIES.has(own) || own.includes(' ') ? null : familyOfPostScript(own);
    return known === null ? { family: own, bold: false, italic: false } : { family: known.family, bold: false, italic: false };
  }
  const named = familyOfPostScript(font.baseFont);
  if (named !== null) return named;
  const fallback = own ?? familyOfName(font.baseFont);
  return fallback === null ? null : { family: fallback, bold: false, italic: false };
}
